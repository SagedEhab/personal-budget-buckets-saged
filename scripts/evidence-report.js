// Combines evidence/<suite>.json (written by the tests while they run) into evidence/test-results.md.
// Run after `npm test`. Nothing in the table is typed by hand.
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'evidence');
const order = ['unit', 'integration', 'security', 'lambda'];
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
let md = '# Automated test results (local run)\n\n';
md += 'Generated by `scripts/evidence-report.js` from the JSON files the tests wrote while running.\n';
md += 'Environment: local Node.js, all four services behind `infra/local-gateway.js`, in-memory data store. **Not a Floci/AWS run.**\n\n';
let total = 0;
let passed = 0;
for (const suite of order) {
  const f = path.join(dir, `${suite}.json`);
  if (!fs.existsSync(f)) { md += `## ${suite}\n\n_No results file: suite not run._\n\n`; continue; }
  const data = JSON.parse(fs.readFileSync(f, 'utf8'));
  const ok = data.rows.filter((r) => r.pass).length;
  total += data.rows.length; passed += ok;
  md += `## ${suite} (${ok}/${data.rows.length} passed, run ${data.ranAt}, Node ${data.node})\n\n`;
  md += '| ID | Area | Scenario | Expected | Actual | Result |\n|---|---|---|---|---|---|\n';
  for (const r of data.rows) md += `| ${r.id} | ${esc(r.area)} | ${esc(r.scenario)} | ${esc(r.expected)} | ${esc(r.actual)} | ${r.pass ? 'PASS' : '**FAIL**'} |\n`;
  md += '\n';
}
md = md.replace('\n\n', `\n\n**Total: ${passed}/${total} checks passed.**\n\n`);
fs.writeFileSync(path.join(dir, 'test-results.md'), md);
console.log(`evidence/test-results.md written: ${passed}/${total} passed`);
